const assert=require('node:assert/strict');
const {padView}=require('../npu_photo/camera_panel.js');
const frame={frame_id:9,session:'a',boot_id:'b',source_rgb565_sha256:'hash'};
const result=(status,extra={})=>({camera_frame:frame,presentation_attack_detection:{...frame,status,frame_age_ms:700,max_age_ms:3000,...extra}});
assert.match(padView(result('model_live')).text,/模型判断为真人/);
assert.match(padView(result('model_non_live')).text,/疑似攻击/);
assert.match(padView(result('inconclusive')).text,/不确定/);
assert.match(padView(result('not_applicable',{reason:'no_face'})).text,/未检测到人脸/);
assert.match(padView(result('not_applicable',{reason:'multiple_faces'})).text,/多人/);
assert.match(padView(result('model_live'),2301).text,/过期/);
assert.match(padView(result('stale')).text,/过期/);
for(const key of ['frame_id','session','boot_id','source_rgb565_sha256'])assert.match(padView(result('model_live',{[key]:'wrong'})).text,/不匹配/);
for(const value of [undefined,-1,NaN])assert.match(padView(result('model_live',{frame_age_ms:value})).text,/过期/);
assert.match(padView(result('model_live'),0,true).text,/暂停/);
assert.match(padView(result('model_live'),0,false,'本次检测失败').text,/失败/);
assert.match(padView(null).text,/等待/);
assert.match(padView(result('unknown')).text,/无法判断/);
const group=result('evaluated',{faces:[{face_index:0,status:'model_live'},{face_index:1,status:'model_non_live'}]});
group.faces=[{},{}];
assert.match(padView(group).text,/人脸 1：模型判断为真人；人脸 2：模型判断为疑似攻击/);
assert.equal(padView(group).error,true);
group.presentation_attack_detection.status='partial';
group.presentation_attack_detection.faces[1]={face_index:1,status:'not_evaluated',reason:'face_limit'};
assert.match(padView(group).text,/人脸 2：超出本帧处理上限，未评估/);
assert.match(padView(group,2301).text,/过期/);
group.presentation_attack_detection.faces[1].face_index=0;
assert.match(padView(group).text,/不匹配/);
group.presentation_attack_detection.faces=undefined;
assert.match(padView(group).text,/不匹配/);
console.log('PAD labels, same-frame binding, expiry, failure and paused states passed.');
